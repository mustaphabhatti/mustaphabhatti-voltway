'use client';
import { Activity, Clock, FlaskConical, Info, Radio, Sparkles, Users, Zap } from 'lucide-react';
import { CONNECTOR_LABELS, DATA_SOURCE_LABELS, PORT_STATUS_LABELS, type ConnectorType, type DataSource, type PortStatus } from '@voltway/shared';
import { Badge } from '@/components/ui';
import { cn, timeAgo } from '@/lib/format';

export const STATUS_STYLE: Record<PortStatus, { dot: string; tone: 'green' | 'blue' | 'violet' | 'red' | 'amber' | 'neutral'; hex: string }> = {
  available: { dot: 'bg-accent', tone: 'green', hex: '#0fa968' },
  charging: { dot: 'bg-electric', tone: 'blue', hex: '#2f6bff' },
  occupied: { dot: 'bg-electric', tone: 'blue', hex: '#2f6bff' },
  reserved: { dot: 'bg-violet', tone: 'violet', hex: '#7c5cff' },
  out_of_service: { dot: 'bg-danger', tone: 'red', hex: '#e5484d' },
  offline: { dot: 'bg-danger', tone: 'red', hex: '#e5484d' },
  no_power: { dot: 'bg-warning', tone: 'amber', hex: '#e08a00' },
  unknown: { dot: 'bg-subtle', tone: 'neutral', hex: '#8a93a0' },
};

export function StatusDot({ status, className }: { status: PortStatus; className?: string }) {
  return <span className={cn('inline-block size-2 rounded-full', STATUS_STYLE[status].dot, className)} />;
}

export function PortStatusBadge({ status }: { status: PortStatus }) {
  return (
    <Badge tone={STATUS_STYLE[status].tone}>
      <StatusDot status={status} /> {PORT_STATUS_LABELS[status]}
    </Badge>
  );
}

const OP_LABEL: Record<string, { label: string; tone: 'green' | 'amber' | 'red' | 'neutral' | 'violet' }> = {
  operational: { label: 'Operational', tone: 'green' },
  partial: { label: 'Partially available', tone: 'amber' },
  offline: { label: 'Temporarily offline', tone: 'red' },
  no_power: { label: 'Electricity unavailable', tone: 'amber' },
  maintenance: { label: 'Under maintenance', tone: 'violet' },
  unknown: { label: 'Status unknown', tone: 'neutral' },
};

export function OperationalBadge({ status }: { status: string }) {
  const s = OP_LABEL[status] ?? OP_LABEL.unknown;
  return <Badge tone={s.tone}>{s.label}</Badge>;
}

/**
 * Data provenance: makes it explicit whether information is live, simulated (demo),
 * reported, or estimated. Only `live` uses the pulsing live indicator.
 */
export function SourceBadge({ source, updatedAt, stale, compact }: { source: DataSource; updatedAt?: string | null; stale?: boolean; compact?: boolean }) {
  const when = updatedAt ? timeAgo(updatedAt) : null;
  if (source === 'live') {
    return (
      <Badge tone={stale ? 'amber' : 'green'} title={stale ? 'Live feed — but no update recently' : 'Real-time data from the charger network'}>
        <span className="live-dot inline-block size-1.5 rounded-full bg-current" />
        {stale ? `Last live update ${when}` : compact ? 'Live' : `Live · ${when}`}
      </Badge>
    );
  }
  if (source === 'simulated') {
    return (
      <Badge tone="violet" title="Generated by the built-in demo simulator. Not real-time data.">
        <FlaskConical className="size-3" /> {compact ? 'Demo feed' : `Demo feed (simulated)${when ? ` · ${when}` : ''}`}
      </Badge>
    );
  }
  if (source === 'operator_reported' || source === 'user_reported') {
    const Icon = source === 'user_reported' ? Users : Clock;
    return (
      <Badge tone={stale ? 'amber' : 'neutral'} title={`${DATA_SOURCE_LABELS[source]} — not a live feed`}>
        <Icon className="size-3" /> {stale ? 'Last reported' : source === 'user_reported' ? 'Driver report' : 'Reported'}{when ? ` ${when}` : ''}
      </Badge>
    );
  }
  if (source === 'estimated') {
    return (
      <Badge tone="outline" className="border-dashed" title="Calculated by Voltway — an estimate, not a measurement">
        <Sparkles className="size-3" /> Estimated
      </Badge>
    );
  }
  return (
    <Badge tone="outline" title="Static listing information">
      <Info className="size-3" /> Listing info
    </Badge>
  );
}

export function EstimatedTag({ children = 'est.' }: { children?: React.ReactNode }) {
  return <span className="ml-1 text-[10.5px] font-medium uppercase tracking-wide text-subtle border border-dashed border-border rounded px-1 py-px align-middle">{children}</span>;
}

export function ConnectorBadge({ type, kw, current }: { type: ConnectorType; kw?: number; current?: 'AC' | 'DC' }) {
  return (
    <span className="inline-flex items-center gap-1 rounded-lg bg-surface-2 px-2 py-1 text-xs font-medium">
      <Zap className={cn('size-3', current === 'DC' ? 'text-electric' : 'text-accent')} />
      {CONNECTOR_LABELS[type]}
      {kw != null && <span className="text-muted">· {kw} kW</span>}
    </span>
  );
}

export function TrafficBadge({ level, source }: { level: string; source: string }) {
  const tone = level === 'heavy' ? 'red' : level === 'moderate' ? 'amber' : level === 'light' ? 'green' : 'neutral';
  return (
    <Badge tone={tone as any} title={source === 'live' ? 'Live traffic' : 'Typical traffic for this time of day (estimated)'}>
      {source === 'live' ? <Radio className="size-3" /> : <Activity className="size-3" />}
      {level === 'unknown' ? 'Traffic n/a' : `${level[0].toUpperCase()}${level.slice(1)} traffic`}
      {source !== 'live' && level !== 'unknown' && <span className="opacity-70">(est.)</span>}
    </Badge>
  );
}
