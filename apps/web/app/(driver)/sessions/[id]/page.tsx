'use client';
import Link from 'next/link';
import { useParams } from 'next/navigation';
import { useState } from 'react';
import { BatteryCharging, CheckCircle2, Clock, FileText, FlaskConical, Gauge, Radio, Square, Zap } from 'lucide-react';
import { Area, AreaChart, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts';
import { estimateCharging, formatDuration, formatMoney } from '@voltway/shared';
import { api } from '@/lib/api';
import { useFetch } from '@/lib/hooks';
import { useRealtime } from '@/lib/realtime';
import { useToast } from '@/lib/toast';
import { clockTime, cn } from '@/lib/format';
import { Badge, Button, Card, CardHeader, ErrorState, Skeleton } from '@/components/ui';
import { RequireRole } from '@/components/layout/RequireRole';
import { EstimatedTag } from '@/components/station/badges';
import { usePlatform } from '@/lib/platform';

function SessionMonitor() {
  const { id } = useParams<{ id: string }>();
  const toast = useToast();
  const { platform } = usePlatform();
  const { data, error, loading, reload, setData } = useFetch<any>(`/sessions/${id}`);
  const [stopping, setStopping] = useState(false);
  const live = useRealtime(`session:${id}`, (event, d) => {
    if (event !== 'session.update' || !data) return;
    const meter = [...(data.session.meter ?? []), { ts: new Date().toISOString(), energyKwh: d.energyKwh, powerKw: d.powerKw, soc: d.currentSoc }];
    setData({ ...data, session: { ...data.session, status: d.status, energy_kwh: d.energyKwh, power_kw: d.powerKw, current_soc: d.currentSoc, cost_total: d.costTotal, ended_at: d.endedAt, meter } });
    if (['completed', 'stopped'].includes(d.status)) setTimeout(reload, 800);
  });
  if (error) return <ErrorState error={error} onRetry={reload} className="py-24" />;
  if (loading || !data) return <div className="max-w-4xl mx-auto p-6 space-y-4"><Skeleton className="h-64" /><Skeleton className="h-48" /></div>;
  const s = data.session;
  const done = ['completed', 'stopped', 'failed'].includes(s.status);
  const soc = Number(s.current_soc ?? s.start_soc ?? 0);
  const remaining = !done && s.battery_kwh ? estimateCharging({
    vehicle: { batteryKwh: Number(s.battery_kwh), maxAcKw: Number(s.max_ac_kw), maxDcKw: Number(s.max_dc_kw), curveProfile: s.curve_profile },
    charger: { powerKw: Number(s.max_power_kw), currentType: s.current_type }, startSoc: soc, targetSoc: Number(s.target_soc), stepSoc: 1,
  }) : null;
  const speed = s.control_source === 'simulator' ? platform?.demo.sessionSpeed ?? 1 : 1;
  const elapsed = ((s.ended_at ? new Date(s.ended_at).getTime() : Date.now()) - new Date(s.started_at).getTime()) / 60000;
  const meter = (s.meter ?? []).map((m: any) => ({ t: (new Date(m.ts).getTime() - new Date(s.started_at).getTime()) / 60000, ...m }));
  const progress = Math.max(0, Math.min(1, (soc - Number(s.start_soc)) / Math.max(1, Number(s.target_soc) - Number(s.start_soc))));

  const stop = async () => {
    setStopping(true);
    try { await api.post(`/sessions/${id}/stop`); toast('success', 'Charging stopped'); reload(); } catch (e: any) { toast('error', 'Could not stop', e.message); } finally { setStopping(false); }
  };

  return (
    <div className="max-w-4xl mx-auto p-4 md:p-6 space-y-4">
      {s.control_source === 'simulator' && (
        <div className="rounded-xl bg-violet-soft text-violet text-[13px] p-3 flex gap-2"><FlaskConical className="size-4 shrink-0 mt-0.5" />Simulated session on a demo charger, running {speed}× faster than real time. Meter values are generated by the simulator, not a real charger.</div>
      )}
      <Card className="overflow-hidden">
        <div className="p-6 md:p-8 grid md:grid-cols-[220px_1fr] gap-8 items-center">
          <div className="relative size-52 mx-auto">
            <svg viewBox="0 0 120 120" className="size-full -rotate-90">
              <circle cx="60" cy="60" r="52" stroke="var(--surface-2)" strokeWidth="10" fill="none" />
              <circle cx="60" cy="60" r="52" stroke={done ? 'var(--accent)' : 'var(--electric)'} strokeWidth="10" fill="none" strokeLinecap="round" strokeDasharray={`${(soc / 100) * 326.7} 326.7`} className="transition-all duration-700" />
            </svg>
            <div className="absolute inset-0 grid place-items-center text-center">
              <div>
                <div className="text-5xl font-semibold tabular tracking-tight">{Math.round(soc)}<span className="text-2xl text-muted">%</span></div>
                <div className="text-xs text-muted mt-1">target {Math.round(s.target_soc)}%</div>
              </div>
            </div>
          </div>
          <div>
            <div className="flex items-center gap-2 flex-wrap">
              <Badge tone={done ? 'green' : s.status === 'pending' ? 'amber' : 'blue'}>{done ? <CheckCircle2 className="size-3" /> : <BatteryCharging className="size-3 animate-pulse" />}{s.status === 'pending' ? 'Waiting for charger' : s.status}</Badge>
              {!done && <Badge tone={live ? 'green' : 'neutral'}><Radio className="size-3" />{live ? 'Streaming updates' : 'Reconnecting…'}</Badge>}
            </div>
            <h1 className="text-xl font-semibold mt-2"><Link href={`/stations/${s.station_id}`} className="hover:underline">{s.station_name}</Link></h1>
            <p className="text-sm text-muted">{s.port_label} · {s.connector_type} {s.max_power_kw} kW · {s.vehicle_brand} {s.vehicle_model}</p>
            <div className="grid grid-cols-2 sm:grid-cols-4 gap-2 mt-5">
              <M icon={Zap} label="Power now" value={`${Number(s.power_kw).toFixed(1)} kW`} />
              <M icon={BatteryCharging} label="Energy" value={`${Number(s.energy_kwh).toFixed(2)} kWh`} />
              <M icon={Clock} label={done ? 'Duration' : 'Elapsed'} value={formatDuration(elapsed * speed)} sub={speed > 1 ? 'simulated time' : undefined} />
              <M icon={Gauge} label={done ? 'Total cost' : 'Remaining'} value={done ? formatMoney(s.cost_total, s.currency) : remaining ? formatDuration(remaining.durationMinutes) : '—'} sub={!done && remaining ? `≈ done ${clockTime(new Date(Date.now() + (remaining.durationMinutes / speed) * 60000))}` : undefined} est={!done} />
            </div>
            <div className="mt-4 h-2 rounded-full bg-surface-2 overflow-hidden"><div className={cn('h-full rounded-full transition-all duration-700', done ? 'bg-accent' : 'bg-electric')} style={{ width: `${progress * 100}%` }} /></div>
            <div className="flex gap-2 mt-5">
              {!done && <Button variant="danger" onClick={stop} loading={stopping}><Square className="size-4" /> Stop charging</Button>}
              {data.invoice && <Link href={`/invoices/${data.invoice.id}`}><Button variant="outline"><FileText className="size-4" /> Invoice {data.invoice.number}</Button></Link>}
              <Link href="/history"><Button variant="ghost">History</Button></Link>
            </div>
          </div>
        </div>
      </Card>
      <Card>
        <CardHeader title="Power delivery" subtitle="Meter readings from the charger session" />
        <div className="px-3 pb-4 h-56">
          {meter.length < 2 ? <p className="text-sm text-muted px-2">Waiting for meter values…</p> : (
            <ResponsiveContainer width="100%" height="100%">
              <AreaChart data={meter}>
                <defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0%" stopColor="var(--electric)" stopOpacity={0.35} /><stop offset="100%" stopColor="var(--electric)" stopOpacity={0} /></linearGradient></defs>
                <XAxis dataKey="t" type="number" domain={[0, 'dataMax']} tickFormatter={(t) => `${Math.round(t * speed)}m`} tick={{ fontSize: 11, fill: 'var(--muted)' }} axisLine={false} tickLine={false} />
                <YAxis width={40} tick={{ fontSize: 11, fill: 'var(--muted)' }} axisLine={false} tickLine={false} />
                <Tooltip contentStyle={{ background: 'var(--surface)', border: '1px solid var(--border)', borderRadius: 12, fontSize: 12 }} formatter={(v: any, n: any) => [n === 'powerKw' ? `${Number(v).toFixed(1)} kW` : v, n === 'powerKw' ? 'Power' : n]} labelFormatter={(t: any) => `${Math.round(t * speed)} min`} />
                <Area type="monotone" dataKey="powerKw" stroke="var(--electric)" strokeWidth={2} fill="url(#g)" isAnimationActive={false} />
              </AreaChart>
            </ResponsiveContainer>
          )}
        </div>
      </Card>
      {done && s.cost_breakdown && (
        <Card className="p-5 text-sm space-y-1 tabular">
          <div className="font-semibold mb-2">Cost breakdown</div>
          <Row k={`Energy ${s.cost_breakdown.energyKwh} kWh @ avg ${formatMoney(s.cost_breakdown.averageRate, s.currency)}`} v={formatMoney(s.cost_breakdown.energyCost, s.currency)} />
          {s.cost_breakdown.serviceCharge > 0 && <Row k="Service charge" v={formatMoney(s.cost_breakdown.serviceCharge, s.currency)} />}
          {s.cost_breakdown.sessionFee > 0 && <Row k="Session fee" v={formatMoney(s.cost_breakdown.sessionFee, s.currency)} />}
          {s.cost_breakdown.tax > 0 && <Row k="Tax" v={formatMoney(s.cost_breakdown.tax, s.currency)} />}
          <div className="h-px bg-border my-2" />
          <Row k={<b>Total</b>} v={<b>{formatMoney(s.cost_total, s.currency)}</b>} />
        </Card>
      )}
    </div>
  );
}
function M({ icon: Icon, label, value, sub, est }: { icon: any; label: string; value: string; sub?: string; est?: boolean }) {
  return <div className="rounded-xl bg-surface-2 p-3"><div className="text-[11.5px] text-muted font-medium flex items-center gap-1"><Icon className="size-3.5" />{label}{est && <EstimatedTag />}</div><div className="text-lg font-semibold tabular mt-0.5">{value}</div>{sub && <div className="text-[11px] text-muted">{sub}</div>}</div>;
}
function Row({ k, v }: { k: React.ReactNode; v: React.ReactNode }) { return <div className="flex justify-between"><span className="text-muted">{k}</span><span>{v}</span></div>; }

export default function SessionPage() {
  return <RequireRole><SessionMonitor /></RequireRole>;
}
