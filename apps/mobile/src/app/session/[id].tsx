import { useState } from 'react';
import { Alert, ScrollView, View } from 'react-native';
import Svg, { Circle } from 'react-native-svg';
import { router, useLocalSearchParams } from 'expo-router';
import { estimateCharging, formatDuration, formatMoney } from '@voltway/shared';
import { api } from '@/lib/api';
import { useFetch } from '@/lib/hooks';
import { useRealtime } from '@/lib/realtime';
import { clock } from '@/lib/format';
import { useColors } from '@/lib/theme';
import { Badge, Button, Card, ErrorView, Fact, Loading, Row, T } from '@/components/ui';

export default function SessionScreen() {
  const { id } = useLocalSearchParams<{ id: string }>();
  const c = useColors();
  const { data, error, loading, reload, setData } = useFetch<any>(`/sessions/${id}`);
  const [stopping, setStopping] = useState(false);
  const live = useRealtime(id ? `session:${id}` : null, (event, d) => {
    if (event !== 'session.update' || !data) return;
    setData({ ...data, session: { ...data.session, status: d.status, energy_kwh: d.energyKwh, power_kw: d.powerKw, current_soc: d.currentSoc, cost_total: d.costTotal, ended_at: d.endedAt } });
    if (['completed', 'stopped'].includes(d.status)) setTimeout(() => reload(true), 800);
  });
  if (error) return <ErrorView error={error} onRetry={() => reload()} />;
  if (loading || !data) return <Loading />;
  const s = data.session;
  const done = ['completed', 'stopped', 'failed'].includes(s.status);
  const soc = Number(s.current_soc ?? s.start_soc ?? 0);
  const remaining = !done && s.battery_kwh ? estimateCharging({ vehicle: { batteryKwh: Number(s.battery_kwh), maxAcKw: Number(s.max_ac_kw), maxDcKw: Number(s.max_dc_kw), curveProfile: s.curve_profile }, charger: { powerKw: Number(s.max_power_kw), currentType: s.current_type }, startSoc: soc, targetSoc: Number(s.target_soc), stepSoc: 1 }) : null;
  const R = 70, C = 2 * Math.PI * R;
  return (
    <ScrollView style={{ backgroundColor: c.bg }} contentContainerStyle={{ padding: 16, gap: 12 }}>
      {s.control_source === 'simulator' && <Card style={{ backgroundColor: c.violetSoft, borderColor: c.violetSoft }}><T size={13} style={{ color: c.violet }}>Simulated session on a demo charger, sped up. Meter values are generated by the simulator, not a real charger.</T></Card>}
      <Card style={{ alignItems: 'center', gap: 12 }}>
        <View style={{ width: 180, height: 180, alignItems: 'center', justifyContent: 'center' }}>
          <Svg width={180} height={180} style={{ position: 'absolute', transform: [{ rotate: '-90deg' }] }}>
            <Circle cx={90} cy={90} r={R} stroke={c.surface2} strokeWidth={14} fill="none" />
            <Circle cx={90} cy={90} r={R} stroke={done ? c.accent : c.electric} strokeWidth={14} fill="none" strokeLinecap="round" strokeDasharray={`${(soc / 100) * C} ${C}`} />
          </Svg>
          <T size={44} weight="800">{Math.round(soc)}<T size={20} muted>%</T></T>
          <T size={12} muted>target {Math.round(s.target_soc)}%</T>
        </View>
        <Row gap={6}><Badge label={s.status === 'pending' ? 'Waiting for charger' : s.status} color={done ? c.accent : c.electric} bg={done ? c.accentSoft : c.electricSoft} />{!done && <Badge label={live ? 'Streaming' : 'Reconnecting…'} />}</Row>
        <T weight="700" size={16}>{s.station_name}</T>
        <T size={13} muted>{s.port_label} · {s.connector_type} {s.max_power_kw} kW · {s.vehicle_brand} {s.vehicle_model}</T>
      </Card>
      <Row gap={8} style={{ flexWrap: 'wrap' }}>
        <Fact label="Power now" value={`${Number(s.power_kw).toFixed(1)} kW`} />
        <Fact label="Energy" value={`${Number(s.energy_kwh).toFixed(2)} kWh`} />
        <Fact label={done ? 'Total cost' : 'Remaining'} value={done ? formatMoney(s.cost_total, s.currency) : remaining ? formatDuration(remaining.durationMinutes) : '—'} est={!done} />
        <Fact label="Started" value={clock(s.started_at)} sub={s.ended_at ? `ended ${clock(s.ended_at)}` : undefined} />
      </Row>
      {!done && <Button title="Stop charging" icon="stop-circle-outline" variant="danger" loading={stopping} onPress={async () => { setStopping(true); try { await api.post(`/sessions/${id}/stop`); reload(true); } catch (e: any) { Alert.alert('Could not stop', e.message); } finally { setStopping(false); } }} />}
      {done && data.invoice && <Card><T weight="700">Invoice {data.invoice.number}</T><T muted size={13}>{formatMoney(data.invoice.amount, data.invoice.currency)} · {data.invoice.payment_status}</T></Card>}
      {done && <Button title="Check in at this station" variant="outline" icon="checkmark-circle-outline" onPress={() => router.push(`/checkin/${s.station_id}`)} />}
    </ScrollView>
  );
}
